param([string]$Destination='D:\DDTank36-交付',[string]$Label='修改前备份',[switch]$StageOnly)
$ErrorActionPreference='Stop'
$taskRoot=$PSScriptRoot
$taskStamp=Get-Date -Format 'yyyyMMdd-HHmmss'
$taskFolder=Join-Path $Destination ('DDTank36-'+$Label+'-'+$taskStamp)
$taskStage=Join-Path $taskFolder 'DDTank36'
if(Test-Path -LiteralPath $taskFolder){throw 'Release destination already exists'}
[void][IO.Directory]::CreateDirectory($taskStage)
$taskStopped=$false
function Copy-Tree36([string]$Source,[string]$Target){
 [void][IO.Directory]::CreateDirectory($Target)
 & robocopy.exe $Source $Target /E /COPY:DAT /DCOPY:DAT /R:1 /W:1 /MT:8 /NFL /NDL /NJH /NJS /NP /XD logs WebLog .vs .git /XF *.mdf *.ldf *.ndf *.dmp | Out-Null
 if($LASTEXITCODE -ge 8){throw "Runtime copy failed: $Source"}
}
try{
 & (Join-Path $taskRoot 'Stop-DDTank36.ps1');$taskStopped=$true
 foreach($taskName in @('Server','Site')){Copy-Tree36 (Join-Path $taskRoot ('package\DanDanTang\'+$taskName)) (Join-Path $taskStage ('package\DanDanTang\'+$taskName))}
 foreach($taskName in @('sources','lib')){Copy-Tree36 (Join-Path $taskRoot ('config\'+$taskName)) (Join-Path $taskStage ('config\'+$taskName))}
 if(Test-Path -LiteralPath (Join-Path $taskRoot 'config\acceptance')){Copy-Tree36 (Join-Path $taskRoot 'config\acceptance') (Join-Path $taskStage 'config\acceptance')}
 Copy-Tree36 (Join-Path $taskRoot 'prerequisites') (Join-Path $taskStage 'prerequisites')
 foreach($taskFile in Get-ChildItem -LiteralPath $taskRoot -File | Where-Object {$_.Extension -in '.ps1','.bat','.config','.text'}){Copy-Item -LiteralPath $taskFile.FullName -Destination $taskStage}
 Copy-Item -LiteralPath (Join-Path $taskRoot '本轮修复验收.md') -Destination $taskStage
 foreach($taskName in @('Branding36.Apply.ps1','Branding36.DatabaseApply.ps1')){Copy-Item -LiteralPath (Join-Path $taskRoot ('config\'+$taskName)) -Destination (Join-Path $taskStage 'config')}
 # Credentials are regenerated by deployment. Existing player data and memories
 # remain in native SQL backups; encrypted model keys need re-entry on a new PC.
 $taskGmConfig=Join-Path $taskStage 'package\DanDanTang\Site\GM\Web.config'
 if(Test-Path -LiteralPath $taskGmConfig){Remove-Item -LiteralPath $taskGmConfig -Force}
 $taskConnection=[Data.SqlClient.SqlConnection]::new('Server=(localdb)\DDTank36;Database=master;Integrated Security=true');$taskConnection.Open()
 try{
  foreach($taskSpec in @(@('tank','Db_Tank_S1'),@('newmem','Db_Membership'),@('count','Db_Count'),@('cross','Db_Cross'),@('log','Db_Logs'))){
   $taskPath=Join-Path $taskStage ('package\DanDanTang\'+$taskSpec[0]+'.bak')
   $taskCmd=$taskConnection.CreateCommand();$taskCmd.CommandTimeout=600
   $taskCmd.CommandText='BACKUP DATABASE ['+$taskSpec[1]+"] TO DISK=N'"+$taskPath.Replace("'","''")+"' WITH COPY_ONLY,INIT,CHECKSUM";[void]$taskCmd.ExecuteNonQuery()
   $taskCmd.CommandText="RESTORE VERIFYONLY FROM DISK=N'"+$taskPath.Replace("'","''")+"' WITH CHECKSUM";[void]$taskCmd.ExecuteNonQuery()
   Write-Output ('Verified SQL backup: '+$taskSpec[1])
  }
 }finally{$taskConnection.Dispose()}
 [pscustomobject]@{version='3.6 Frank CN';label=$Label;createdUtc=[DateTime]::UtcNow.ToString('o');containsLivePlayerData=$true;containsRuntimeToken=$false;gmPasswordRegenerated=$true;modelKeys='DPAPI machine-bound; re-enter after migration';databaseRestore='Only missing databases; existing databases are never overwritten'} | ConvertTo-Json | Set-Content -LiteralPath (Join-Path $taskStage '发行说明.json') -Encoding UTF8
}finally{if($taskStopped){& (Join-Path $taskRoot 'Start-OneClick36.ps1')}}
$taskFiles=Get-ChildItem -LiteralPath $taskStage -File -Recurse
$taskManifest=@($taskFiles | ForEach-Object {[pscustomobject]@{path=$_.FullName.Substring($taskStage.Length+1);bytes=$_.Length;sha256=(Get-FileHash -LiteralPath $_.FullName -Algorithm SHA256).Hash}})
$taskManifest | ConvertTo-Json -Depth 3 | Set-Content -LiteralPath (Join-Path $taskStage '文件校验.json') -Encoding UTF8
if(!$StageOnly){
 $taskZipPath=$taskFolder+'.zip'
 Add-Type -AssemblyName System.IO.Compression,System.IO.Compression.FileSystem
 [IO.Compression.ZipFile]::CreateFromDirectory($taskFolder,$taskZipPath,[IO.Compression.CompressionLevel]::Fastest,$false)
 $taskZip=[IO.Compression.ZipFile]::OpenRead($taskZipPath)
 try{if(@($taskZip.Entries | Where-Object {$_.Name.Length -gt 0}).Count -ne $taskFiles.Count+1){throw 'ZIP file inventory count mismatch'}}finally{$taskZip.Dispose()}
 Get-FileHash -LiteralPath $taskZipPath -Algorithm SHA256 | Format-List
 Write-Output ('Release ZIP: '+$taskZipPath)
}
Write-Output ('Release folder: '+$taskStage)
